/**
 * docs/api-coverage.md from coverage.json (docs/api-v1.md §10).
 *
 * The data is the source; the page is written by `npm run api:docs` and the
 * parity test fails when it is stale. The prose is Russian, as docs/ is; the
 * names and reasons are the data's, in English.
 */

import type { Coverage, CoverageEntry, CoverageStatus } from './parity';

const HEADINGS: Readonly<Record<CoverageStatus, string>> = {
  exposed: 'Выставлено в API v1',
  planned: 'Запланировано (право зарезервировано)',
  internal: 'Внутреннее',
};

function cell(text: string): string {
  return text.replaceAll('|', '\\|').replaceAll('\n', ' ');
}

function rows(entries: readonly [string, CoverageEntry][], status: CoverageStatus): string[] {
  if (status === 'internal') {
    return ['| Имя | Причина |', '| --- | --- |', ...entries.map(([name, e]) => `| \`${name}\` | ${cell(e.reason)} |`)];
  }
  if (status === 'planned') {
    return [
      '| Имя | Право | Что это |',
      '| --- | --- | --- |',
      ...entries.map(([name, e]) => `| \`${name}\` | \`${e.scope ?? ''}\` | ${cell(e.reason)} |`),
    ];
  }
  return [
    '| Имя | Право | Операции |',
    '| --- | --- | --- |',
    ...entries.map(
      ([name, e]) =>
        `| \`${name}\` | ${e.scope === undefined ? 'любой ключ' : `\`${e.scope}\``} | ${(e.operations ?? []).map((op) => `\`${op}\``).join(', ')} |`,
    ),
  ];
}

function section(title: string, list: Readonly<Record<string, CoverageEntry>>): string[] {
  const lines = [`## ${title}`, ''];
  for (const status of ['exposed', 'planned', 'internal'] as const) {
    const entries = Object.entries(list).filter(([, e]) => e.status === status);
    lines.push(`### ${HEADINGS[status]} — ${entries.length}`, '', ...rows(entries, status), '');
  }
  return lines;
}

export function renderCoverageDoc(coverage: Coverage): string {
  const count = (list: Readonly<Record<string, CoverageEntry>>, status: CoverageStatus) =>
    Object.values(list).filter((e) => e.status === status).length;
  const total = (status: CoverageStatus) => count(coverage.functions, status) + count(coverage.tables, status);
  return [
    '# Покрытие API: функции и таблицы схемы public',
    '',
    '<!-- Generated by npm run api:docs from packages/shared/src/api/coverage.json. Do not edit by hand. -->',
    '',
    'Каждая функция и таблица (с представлениями) схемы `public` после всех миграций стоит в одной из',
    'трёх групп: выставлено в API v1 (право и операции), запланировано (зарезервированное право) или',
    'внутреннее (с причиной). Тест паритета',
    '(`apps/web/src/features/api-keys/__tests__/api-parity.test.ts`) падает на объекте без записи, на записи',
    'без объекта и на праве не из реестра. Правило — CLAUDE.md, «Паритет API»; проект — `docs/api-v1.md`.',
    '',
    `| | Выставлено | Запланировано | Внутреннее | Всего |`,
    '| --- | --- | --- | --- | --- |',
    `| Функции | ${count(coverage.functions, 'exposed')} | ${count(coverage.functions, 'planned')} | ${count(coverage.functions, 'internal')} | ${Object.keys(coverage.functions).length} |`,
    `| Таблицы и представления | ${count(coverage.tables, 'exposed')} | ${count(coverage.tables, 'planned')} | ${count(coverage.tables, 'internal')} | ${Object.keys(coverage.tables).length} |`,
    `| Всего | ${total('exposed')} | ${total('planned')} | ${total('internal')} | ${Object.keys(coverage.functions).length + Object.keys(coverage.tables).length} |`,
    '',
    ...section('Функции', coverage.functions),
    ...section('Таблицы и представления', coverage.tables),
  ].join('\n');
}
