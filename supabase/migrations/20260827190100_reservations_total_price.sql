-- Цена брони.
--
-- Выяснено на живых данных: надёжного признака «это блокировка, а не гость»
-- Hostaway не даёт. channelId = 2000 (прямой канал) содержит вперемешку
-- промо-показы, фотосъёмки, хозяйские заезды и настоящие отменённые брони
-- с ненулевой ценой. Имя гостя у блокировок произвольное: встречались
-- 'block', 'Upgrade', 'Foceni', 'andrej promo show', 'NY Block'.
--
-- Осмысленных машинных сигнала два: status (семь значений, включая ownerStay,
-- inquiry и cancelled) и цена — у блокировок она почти всегда нулевая.
-- Колонка добавляется, чтобы генератор задач в F4 мог опираться на факты,
-- а не угадывать по имени гостя.

alter table public.reservations
  add column total_price numeric(12,2);

comment on column public.reservations.total_price is
  'Сумма брони. Ноль у большинства внутренних блокировок, но признак не абсолютный: '
  'встречаются отменённые брони с ненулевой ценой и промо-заезды с нулевой.';
