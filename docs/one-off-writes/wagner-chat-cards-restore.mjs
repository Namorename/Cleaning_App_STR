// CLIENT:Wagnerstays — the undo of wagner-chat-cards-delete.sql (owner, 2026-11-26, «В2»): turns
// the backup taken by wagner-chat-cards-backup.sql into one SQL statement that puts the deleted
// cards from chats back and links again what the delete unlinked. The rows stay out of git: the
// backup and the statement live in ~/.str-ops/backups/2026-11-26-chat-cards/.
//
//   node docs/one-off-writes/wagner-chat-cards-restore.mjs <backup.json> <restore.sql>
//   npx supabase db query --linked -f <restore.sql>       (a WRITE: on the owner's word only)
//
// A card whose signal was purged since (the keys of messages live 90 days) has nothing to stand
// on and is skipped; a card back in the table is left as it is. The table's triggers set its
// link dates again (signal_findings_dates, signal_findings_task_link). Chats stay off: the admin
// turns them on in the panel if the cards should show again.
import { readFileSync, writeFileSync } from 'node:fs';

const [backupPath, outPath] = process.argv.slice(2);
if (!backupPath || !outPath) {
  console.error('usage: node wagner-chat-cards-restore.mjs <backup.json> <restore.sql>');
  process.exit(2);
}

/** cloud-read answers the rows of the query: [{ backup: {...} }]. */
function readBackup(path) {
  const parsed = JSON.parse(readFileSync(path, 'utf8'));
  const backup = Array.isArray(parsed) ? parsed[0]?.backup : parsed.backup;
  if (!backup || !Array.isArray(backup.findings) || typeof backup.count !== 'number') {
    throw new Error(`${path} is not a backup of wagner-chat-cards-backup.sql`);
  }
  if (backup.findings.length !== backup.count) {
    throw new Error(`the backup holds ${backup.findings.length} rows, it says ${backup.count}`);
  }
  return backup;
}

const backup = readBackup(backupPath);
const payload = JSON.stringify({
  findings: backup.findings,
  feedback: backup.feedback ?? [],
  labels: backup.labels ?? [],
});
const QUOTE = '$backup$';
if (payload.includes(QUOTE)) {
  throw new Error('the backup holds the quote of the statement');
}

const sql = `-- CLIENT:Wagnerstays — restore of the cards from chats deleted on 2026-11-26 (${backup.count} rows,
-- taken ${backup.taken_at}). Generated by docs/one-off-writes/wagner-chat-cards-restore.mjs.
do $restore$
declare
  v_rows     jsonb := ${QUOTE}${payload}${QUOTE}::jsonb;
  v_back     integer;
  v_feedback integer;
  v_labels   integer;
begin
  perform set_config('lock_timeout', '3s', true);

  insert into public.signal_findings
  select r.*
  from jsonb_populate_recordset(null::public.signal_findings, v_rows -> 'findings') r
  where exists (select 1 from public.guest_signals s where s.id = r.signal_id)
  on conflict (id) do nothing;
  get diagnostics v_back = row_count;

  update public.signal_feedback b
  set finding_id = (x ->> 'finding_id')::uuid
  from jsonb_array_elements(v_rows -> 'feedback') x
  where b.id = (x ->> 'id')::bigint and b.finding_id is null
    and exists (select 1 from public.signal_findings f where f.id = (x ->> 'finding_id')::uuid);
  get diagnostics v_feedback = row_count;

  update public.issue_facts i
  set finding_id = (x ->> 'finding_id')::uuid
  from jsonb_array_elements(v_rows -> 'labels') x
  where i.id = (x ->> 'id')::uuid and i.finding_id is null
    and exists (select 1 from public.signal_findings f where f.id = (x ->> 'finding_id')::uuid);
  get diagnostics v_labels = row_count;

  raise notice 'restored % of % cards; % verdicts and % labels linked again',
    v_back, jsonb_array_length(v_rows -> 'findings'), v_feedback, v_labels;
end;
$restore$;
`;

writeFileSync(outPath, sql);
console.log(
  `written ${outPath}: ${backup.count} cards, ${backup.feedback?.length ?? 0} verdicts, ` +
    `${backup.labels?.length ?? 0} labels`,
);
